//! Host for the baton experiment: a deterministic simulator that runs several
//! instances of one effectful Roc app, one per node, inside a single process.
//!
//! The app is written like a normal basic-cli program: `main!` loops and blocks
//! in `Net.recv!` or `Clock.sleep!`. A blocked node is stuck *inside* a hosted
//! function with its whole Roc call stack underneath, and Roc has no coroutines
//! to pause it. So every node runs on its own OS thread, which only serves to
//! keep that stack alive while the node is paused.
//!
//! The threads never run in parallel. They pass a baton:
//! - every hosted function sends a `Request` to the scheduler (main thread) and
//!   then blocks until the scheduler sends back a `Reply`;
//! - the scheduler resumes exactly one node, waits for that node's next request,
//!   and only then decides what happens next.
//!
//! So at any moment exactly one thread runs: the scheduler or one node. Every
//! choice (which ready node runs next, message delays, drops) comes from a PRNG
//! seeded from the command line, and time is virtual: sleeping or waiting jumps
//! the clock forward instead of waiting. The same seed therefore gives the same
//! run, which the trace hash printed at the end lets you check.
//!
//! Usage: `app/main <seed> [--trace]`

use std::cell::RefCell;
use std::cmp::Reverse;
use std::collections::{BinaryHeap, VecDeque};
use std::ffi::{c_void, CStr};
use std::ptr::NonNull;
use std::sync::mpsc::{channel, Receiver, Sender};
use std::thread;

// Generated by `roc glue $ROC_GLUE_SPEC ./src/ platform/main.roc` from the
// platform. Regenerate it after changing the platform.
mod roc_platform_abi;

use crate::roc_platform_abi::{
    make_roc_host, roc_main, DefaultAllocators, DefaultHandlers, HostRecv, RocHost, RocStr,
};

/// Number of nodes, i.e. app instances.
const CLUSTER_SIZE: usize = 3;

/// Upper bound on scheduler steps, so an app that never stops can't hang the run.
const MAX_STEPS: u64 = 10_000_000;

/// Each node gets one random delay per message in this range (virtual ms).
const MIN_DELAY_MS: u64 = 1;
const MAX_DELAY_MS: u64 = 30;

/// One message in this many is dropped.
const DROP_ONE_IN: u64 = 10;

/// Stack for each node thread. Roc recursion runs on it, so be generous.
const NODE_STACK_BYTES: usize = 64 * 1024 * 1024;

// ---------------------------------------------------------------------------
// Roc runtime glue

// `RocHost` bundles the allocator and handler callbacks that the glue's helper
// methods (`RocStr::from_str`, `decref`, ...) use. It lives in a global so the
// `extern "C"` functions, which take no context argument, can reach it. All node
// threads share it; that's safe because only one thread runs at a time.
static mut ROC_HOST: *mut RocHost = core::ptr::null_mut();

fn roc_host_ptr() -> *mut RocHost {
    unsafe {
        if ROC_HOST.is_null() {
            eprintln!("roc host error: RocHost not initialized");
            std::process::exit(1);
        }
        ROC_HOST
    }
}

fn roc_host() -> &'static RocHost {
    unsafe { &*roc_host_ptr() }
}

#[no_mangle]
pub extern "C" fn roc_alloc(length: usize, alignment: usize) -> NonNull<c_void> {
    DefaultAllocators::roc_alloc(roc_host_ptr(), length, alignment)
}


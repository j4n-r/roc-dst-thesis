//! Host for the baton experiment: a deterministic simulator that runs several
//! instances of one effectful Roc app, one per node, inside a single process.
//!
//! The app is written like a normal basic-cli program: `main!` loops and blocks
//! in `Net.recv!` or `Clock.sleep!`. A blocked node is stuck *inside* a hosted
//! function with its whole Roc call stack underneath, and Roc has no coroutines
//! to pause it. So every node runs on its own OS thread, which only serves to
//! keep that stack alive while the node is paused.
//!
//! The threads never run in parallel. They pass a baton:
//! - every hosted function sends a `Request` to the scheduler (main thread) and
//!   then blocks until the scheduler sends back a `Reply`;
//! - the scheduler resumes exactly one node, waits for that node's next request,
//!   and only then decides what happens next.
//!
//! So at any moment exactly one thread runs: the scheduler or one node. Every
//! choice (which ready node runs next, message delays, drops) comes from a PRNG
//! seeded from the command line, and time is virtual: sleeping or waiting jumps
//! the clock forward instead of waiting. The same seed therefore gives the same
//! run, which the trace hash printed at the end lets you check.
//!
//! A node can start more fibers with `Fiber.spawn!`. The scheduler's unit is a
//! fiber, not a node: each fiber gets its own OS thread and is one more baton
//! holder. The app boxes the fiber's function and passes it to
//! `hosted_spawn`; the new thread hands the box back to Roc through the
//! platform's `roc_run_fiber` entry point, which unboxes and calls it. Messages
//! go to a node's mailbox; the fiber that has waited longest in `recv!` gets them.
//!
//! Usage: `app/main <seed> [--trace]`


//! Host for the messaging experiment: a tiny network simulator.
//!
//! Each node is an instance of the same Roc app. Nodes are pure: `init` and
//! `receive` only return data (new state, messages to send, log lines) and never
//! perform I/O themselves. The host owns everything else: it stores each node's
//! state, holds messages "in flight", and decides which message is delivered
//! next. Here that decision is plain FIFO; later it becomes a seeded scheduler
//! that can also drop, delay or reorder messages.
//!
//! Calls go one way only: the host calls the `provides` symbols
//! (`roc_init_for_host`, `roc_receive_for_host`). The platform has no hosted
//! effects, so Roc only calls back into the runtime symbols (`roc_alloc`, ...).

use std::collections::VecDeque;
use std::ffi::c_void;
use std::ptr::NonNull;

// Generated by `roc glue $ROC_GLUE_SPEC ./src/ platform/main.roc` from the
// platform. Regenerate it after changing the platform.
mod roc_platform_abi;

use crate::roc_platform_abi::{
    decref_list_of_str, make_roc_host, roc_init_for_host, roc_receive_for_host,
    DefaultAllocators, DefaultHandlers, InitForHost, RocBox, RocHost,
};

/// Number of nodes in the simulated cluster.
const CLUSTER_SIZE: u64 = 3;

/// Upper bound on deliveries, so a buggy app that never stops sending can't hang the run.
const MAX_DELIVERIES: usize = 1000;

/// A message in flight. `msg` is a `Box(Msg)`: the app's own message type, which
/// the host routes without knowing its layout.
struct Envelope {
    from: u64,
    to: u64,
    msg: RocBox,
}

// `RocHost` bundles the allocator and handler callbacks that the glue's helper
// methods (`decref`, ...) use. Compiled Roc code doesn't use it; it calls the
// `roc_*` symbols below directly. It lives in a global so those `extern "C"`
// functions, which take no context argument, can reach it.
static mut ROC_HOST: *mut RocHost = core::ptr::null_mut();

fn set_roc_host(roc_host: *mut RocHost) {
    unsafe {
        ROC_HOST = roc_host;
    }
}

fn roc_host_ptr() -> *mut RocHost {
    unsafe {
        if ROC_HOST.is_null() {
            eprintln!("roc host error: RocHost not initialized");
            std::process::exit(1);
        }
        ROC_HOST
    }
}

fn roc_host() -> &'static RocHost {
    unsafe { &*roc_host_ptr() }
}

// Runtime symbols: Roc allocates all heap memory (strings, lists, boxes) through
// these three. The defaults wrap Rust's global allocator.

#[no_mangle]
pub extern "C" fn roc_alloc(length: usize, alignment: usize) -> NonNull<c_void> {
    DefaultAllocators::roc_alloc(roc_host_ptr(), length, alignment)
}

#[no_mangle]
pub extern "C" fn roc_dealloc(ptr: *mut c_void, alignment: usize) {
    DefaultAllocators::roc_dealloc(roc_host_ptr(), ptr, alignment);
}

#[no_mangle]
pub extern "C" fn roc_realloc(ptr: *mut c_void, new_length: usize, alignment: usize) -> NonNull<c_void> {
    DefaultAllocators::roc_realloc(roc_host_ptr(), ptr, new_length, alignment)
}

// Runtime symbols for Roc's built-in reporting: `dbg` expressions, failed
// `expect`s, and `crash`. The defaults print to stderr; roc_crashed also exits.

#[no_mangle]
pub extern "C" fn roc_dbg(bytes: *const u8, len: usize) {
    DefaultHandlers::roc_dbg(roc_host_ptr(), bytes, len);
}

#[no_mangle]
pub extern "C" fn roc_expect_failed(bytes: *const u8, len: usize) {
    DefaultHandlers::roc_expect_failed(roc_host_ptr(), bytes, len);
}

#[no_mangle]
pub extern "C" fn roc_crashed(bytes: *const u8, len: usize) {
    DefaultHandlers::roc_crashed(roc_host_ptr(), bytes, len);
}

/// Program entry point: musl's startup code (crt1.o) calls `main`.
#[no_mangle]
pub extern "C" fn main(_argc: i32, _argv: *const *const i8) -> i32 {
    rust_main()
}

/// Take apart one result of `init`/`receive` for node `node`: print its log
/// lines, put its outgoing messages on the network, and return its new state.
///
/// `init` and `receive` return the same record shape, so `InitForHost` covers both.
fn absorb(step: InitForHost, node: u64, network: &mut VecDeque<Envelope>) -> RocBox {
    for line in step.log.as_slice() {
        println!("    node {node} log: {}", line.as_str());
    }

    for out in step.outbox.as_slice() {
        if out.to >= CLUSTER_SIZE {
            eprintln!("node {node} sent to unknown node {}", out.to);
            std::process::exit(1);
        }
        // The Box(Msg) moves from the list into the network queue. The list was
        // just built by Roc and is not shared, so taking its elements is safe.
        network.push_back(Envelope { from: node, to: out.to, msg: out.msg });
    }

    unsafe {
        // Free the log strings, and the outbox list itself. The glue marks the
        // outbox elements as not refcounted, so this frees only the list storage,
        // not the message boxes we just moved out.
        decref_list_of_str(step.log, roc_host());
        step.outbox.decref(roc_host());
    }

    step.model
}

pub fn rust_main() -> i32 {
    let mut roc_host = make_roc_host(core::ptr::null_mut());
    set_roc_host(&mut roc_host);

    // Messages in flight, delivered first-in first-out.
    let mut network: VecDeque<Envelope> = VecDeque::new();

    // Start every node. Each node's state is an opaque Box(Model) that the host
    // holds between calls but never reads. A node may already send messages here.
    let mut nodes: Vec<RocBox> = Vec::new();
    for id in 0..CLUSTER_SIZE {
        println!("init node {id}");
        let step = unsafe { roc_init_for_host(id, CLUSTER_SIZE) };
        nodes.push(absorb(step, id, &mut network));
    }

    // Deliver messages until the network is empty. Each delivery passes the
    // receiver's state and the message into Roc (both consumed) and stores the
    // receiver's new state.
    let mut deliveries = 0;
    while let Some(envelope) = network.pop_front() {
        deliveries += 1;
        if deliveries > MAX_DELIVERIES {
            eprintln!("stopped after {MAX_DELIVERIES} deliveries");
            return 1;
        }

        let Envelope { from, to, msg } = envelope;
        println!("deliver #{deliveries}: node {from} -> node {to}");
        let receiver = nodes[to as usize];
        let step = unsafe { roc_receive_for_host(receiver, from, msg) };
        nodes[to as usize] = absorb(step, to, &mut network);
    }

    println!("network empty after {deliveries} deliveries");

    // The final node states are leaked: the process exits right after, and
    // freeing a Box(Model) in general needs a Roc-side drop entrypoint.
    let _ = nodes;

    set_roc_host(core::ptr::null_mut());
    0
}

//! Host for the counters experiment: drives several independent instances of
//! one Roc application and receives their `Log.line!` effect calls.
//!
//! The host and the compiled Roc app are linked into one executable and talk
//! through plain C symbols:
//! - the host calls Roc through the `provides` symbols (`roc_init_for_host`,
//!   `roc_update_for_host`), declared in the generated `roc_platform_abi.rs`;
//! - Roc calls the host through the `hosted` symbols (`roc_log`) and the runtime
//!   symbols every host must export (`roc_alloc`, `roc_crashed`, ...), all
//!   defined in this file.

use std::ffi::c_void;
use std::ptr::NonNull;

// Generated by `roc glue $ROC_GLUE_SPEC ./src/ platform/main.roc` from the
// platform. Holds the Roc data types (RocStr, RocBox, ...) and the signatures of
// the provided and hosted functions. Regenerate it after changing the platform.
mod roc_platform_abi;

use crate::roc_platform_abi::{
    make_roc_host, roc_init_for_host, roc_update_for_host, DefaultAllocators, DefaultHandlers,
    RocBox, RocHost, RocStr,
};

/// Event codes understood by `update_for_host!` in platform/main.roc.
const INCREMENT: u8 = 0;

// `RocHost` bundles the allocator and handler callbacks that the glue's helper
// methods (`RocStr::from_str`, `decref`, ...) use. Compiled Roc code doesn't use
// it; it calls the `roc_*` symbols below directly. It lives in a global so those
// `extern "C"` functions, which take no context argument, can reach it.
static mut ROC_HOST: *mut RocHost = core::ptr::null_mut();

fn set_roc_host(roc_host: *mut RocHost) {
    unsafe {
        ROC_HOST = roc_host;
    }
}

fn roc_host_ptr() -> *mut RocHost {
    unsafe {
        if ROC_HOST.is_null() {
            eprintln!("roc host error: RocHost not initialized");
            std::process::exit(1);
        }
        ROC_HOST
    }
}

fn roc_host() -> &'static RocHost {
    unsafe { &*roc_host_ptr() }
}

// `#[no_mangle] pub extern "C"` exports a function under exactly this name with
// the C calling convention, so the linker can match it to Roc's call site.

/// Hosted function: Host.log!
///
/// Roc hands over ownership of `message`; once printed, the host releases it with
/// `decref`, which frees the string when nothing else references it.
#[no_mangle]
pub extern "C" fn roc_log(message: RocStr) {
    println!("{}", message.as_str());
    unsafe { message.decref(roc_host()) };
}

// Runtime symbols: Roc allocates all heap memory (strings, lists, boxes) through
// these three. The defaults wrap Rust's global allocator.

#[no_mangle]
pub extern "C" fn roc_alloc(length: usize, alignment: usize) -> NonNull<c_void> {
    DefaultAllocators::roc_alloc(roc_host_ptr(), length, alignment)
}

#[no_mangle]
pub extern "C" fn roc_dealloc(ptr: *mut c_void, alignment: usize) {
    DefaultAllocators::roc_dealloc(roc_host_ptr(), ptr, alignment);
}

#[no_mangle]
pub extern "C" fn roc_realloc(ptr: *mut c_void, new_length: usize, alignment: usize) -> NonNull<c_void> {
    DefaultAllocators::roc_realloc(roc_host_ptr(), ptr, new_length, alignment)
}

// Runtime symbols for Roc's built-in reporting: `dbg` expressions, failed
// `expect`s, and `crash` (e.g. an unknown event code). The defaults print to
// stderr; roc_crashed also exits.

#[no_mangle]
pub extern "C" fn roc_dbg(bytes: *const u8, len: usize) {
    DefaultHandlers::roc_dbg(roc_host_ptr(), bytes, len);
}

#[no_mangle]
pub extern "C" fn roc_expect_failed(bytes: *const u8, len: usize) {
    DefaultHandlers::roc_expect_failed(roc_host_ptr(), bytes, len);
}

#[no_mangle]
pub extern "C" fn roc_crashed(bytes: *const u8, len: usize) {
    DefaultHandlers::roc_crashed(roc_host_ptr(), bytes, len);
}

/// Program entry point: musl's startup code (crt1.o) calls `main`.
#[no_mangle]
pub extern "C" fn main(_argc: i32, _argv: *const *const i8) -> i32 {
    rust_main()
}

pub fn rust_main() -> i32 {
    let mut roc_host = make_roc_host(core::ptr::null_mut());
    set_roc_host(&mut roc_host);

    // Start one app instance per name. Each instance's state is an opaque
    // Box(Model): a pointer to Roc-owned memory that the host holds between calls
    // but never reads. Ownership of the name string passes to Roc.
    let mut instances: Vec<RocBox> = ["A", "B", "C"]
        .iter()
        .map(|name| unsafe { roc_init_for_host(RocStr::from_str(name, &roc_host)) })
        .collect();

    // Hardcoded event sequence: two rounds of Increment to every instance.
    // Instances never see each other's state; only the host knows there are three.
    for _round in 0..2 {
        for model in instances.iter_mut() {
            // update_for_host! consumes the old box and returns the new state.
            // Inside, the app calls Log.line!, which lands in roc_log above.
            *model = unsafe { roc_update_for_host(*model, INCREMENT) };
        }
    }

    // The final boxes are leaked: the process exits right after, and freeing a
    // Box(Model) that holds a Str needs a Roc-side drop entrypoint.
    let _ = instances;

    set_roc_host(core::ptr::null_mut());
    0
}
